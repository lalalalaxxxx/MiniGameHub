"""Generate the atomic offline release. Run before committing public-file changes."""
from pathlib import Path
import argparse
import hashlib
import json

ROOT = Path(__file__).resolve().parents[1]
EXTENSIONS = {'.html', '.js', '.css', '.json', '.svg', '.png', '.mp3', '.wav'}


def build():
    files = [ROOT / 'index.html', ROOT / 'manifest.webmanifest']
    for folder in ('assets', 'games'):
        files.extend(p for p in (ROOT / folder).rglob('*') if p.suffix in EXTENSIONS and p.is_file())
    assets = [{'path': p.relative_to(ROOT).as_posix(), 'sha256': hashlib.sha256(p.read_bytes()).hexdigest()}
              for p in sorted(files)]
    template = (ROOT / 'tools/service-worker.template.js').read_text(encoding='utf-8')
    manifest = json.dumps(assets, ensure_ascii=False, separators=(',', ':'))
    version = hashlib.sha256((manifest + template).encode()).hexdigest()[:16]
    return ('// Generated by tools/build_offline.py; do not edit.\n'
            f'const RELEASE = "{version}";\nconst ASSETS = {manifest};\n' + template)


if __name__ == '__main__':
    parser = argparse.ArgumentParser()
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    expected = build()
    target = ROOT / 'sw.js'
    if args.check:
        if not target.exists() or target.read_text(encoding='utf-8') != expected:
            raise SystemExit('Offline manifest is stale. Run: python tools/build_offline.py')
        print('Offline manifest matches all public files.')
    else:
        target.write_bytes(expected.encode())
        print('Generated sw.js with a content-based release ID and SHA-256 asset checks.')
